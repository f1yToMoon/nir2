"""Deterministic data of a run (tz/05 §1, tz/06 step 3.2).

Event id ranges (bigint), disjoint, so that every row tells who wrote it (invariants):
  golden              [0, rows_total)
  stream i            STREAM_BASE * (i + 1) + n           (Flink/Kafka events)
  agent w of stream i STREAM_BASE * (i + 1) + AGENT_BASE * (w + 1) + n
  controlled op k     OP_BASE + k * OP_STRIDE + n         (rows inserted by MERGE)

Golden rows are generated by Spark SQL expressions of (id, seed): the same seed gives the same
table. Partition fragmentation: the table is written in `files_per_partition` batches; with
`write.distribution-mode=hash` each batch writes one file per partition.
"""
from __future__ import annotations

from collections.abc import Iterator
from dataclasses import dataclass
from datetime import date, datetime, timedelta, timezone
from typing import Any

import numpy as np

from runner.intents import bucket_long, rng
from runner.scenario import Scenario, Stream

STREAM_BASE = 1_000_000_000_000          # 1e12
AGENT_BASE = 100_000_000_000             # 1e11
OP_BASE = 9_000_000_000_000              # 9e12
OP_STRIDE = 1_000_000

SPARK_TYPES = {"bigint": "BIGINT", "date": "DATE", "timestamp": "TIMESTAMP_NTZ",
               "double": "DOUBLE", "string": "STRING", "int": "INT"}
# `timestamp` of the scenario schema is Iceberg `timestamp` (without zone): Flink writes
# TIMESTAMP(6) (infra/flink/sql/streaming_append.sql), which maps to it, not to timestamptz.


def ddl(sc: Scenario, table: str) -> str:
    cols = ", ".join(f"{c.name} {SPARK_TYPES[c.type]}{' NOT NULL' if c.required else ''}"
                     for c in sc.table.schema_)
    parts = ", ".join(sc.table.partition_spec)
    props = {"format-version": str(sc.table.format_version), **sc.table.properties}
    tp = ", ".join(f"'{k}' = '{v}'" for k, v in props.items())
    return f"CREATE TABLE {table} ({cols}) USING iceberg PARTITIONED BY ({parts}) TBLPROPERTIES ({tp})"


def golden_select(sc: Scenario, lo: int, hi: int, data_seed: int) -> str:
    """SELECT of golden rows with id in [lo, hi)."""
    sd = sc.table
    first = sd.days[0].isoformat()
    s = data_seed
    pb = sc.seed_data.payload_bytes
    # ~random text: independent SHA-256 hex digests (64 chars each), not a repeated one
    hexes = ", ".join(f"sha2(concat(CAST(id AS STRING), '-{s}-{i}'), 256)" for i in range(pb // 64 + 1))
    return f"""
        SELECT id AS event_id,
               pmod(xxhash64(id, {s}, 1), {sc.seed_data.key_cardinality}) AS key,
               date_add(DATE '{first}', CAST(pmod(xxhash64(id, {s}, 2), {sd.logical_days}) AS INT)) AS dt,
               CAST(date_add(DATE '{first}', CAST(pmod(xxhash64(id, {s}, 2), {sd.logical_days}) AS INT))
                    AS TIMESTAMP_NTZ) + make_dt_interval(0, 0, 0, pmod(xxhash64(id, {s}, 3), 86400))
                    AS event_ts,
               CAST(pmod(xxhash64(id, {s}, 4), 1000000) AS DOUBLE) / 100.0 AS amount,
               'new' AS status,
               0 AS version,
               substr(concat({hexes}), 1, {pb}) AS payload
        FROM range({lo}, {hi})"""


def seed_batches(sc: Scenario) -> list[tuple[int, int]]:
    n = sc.seed_data.rows_total
    f = sc.seed_data.files_per_partition
    return [(n * j // f, n * (j + 1) // f) for j in range(f)]


# ── events of streams ────────────────────────────────────────────────────────

@dataclass
class EventGen:
    """Seeded generator of stream events (Kafka producer and Spark agents)."""
    sc: Scenario
    stream: Stream
    stream_idx: int
    writer: int | None          # None: Flink stream; w: agent w
    seed: int

    def __post_init__(self) -> None:
        self._r = rng(self.seed, "stream", self.stream.id, self.writer)
        base = STREAM_BASE * (self.stream_idx + 1)
        if self.writer is not None:
            base += AGENT_BASE * (self.writer + 1)
        self.next_id = base
        self.n_buckets = self.sc.table.n_buckets
        self.card = self.sc.seed_data.key_cardinality

    def _keys(self, n: int) -> np.ndarray:
        k = self.stream.keys
        if k.dist == "zipf":
            a = k.a or 1.1
            ranks = self._r.zipf(a, size=n)
            return np.asarray((ranks - 1) % self.card, dtype=np.int64)
        return self._r.integers(0, self.card, size=n, dtype=np.int64)

    def batch(self, n: int, now: datetime | None = None) -> list[dict[str, Any]]:
        """n events; dt by partition_target relative to logical_today."""
        now = now or datetime.now(timezone.utc)  # noqa: UP017 — runner image is Python 3.10
        pt = self.stream.partition_target
        today = self.sc.table.logical_today - timedelta(days=pt.hot_offset_days)
        keys = self._keys(n)
        late = self._r.uniform(size=n) < pt.late_fraction
        late_days = (self._r.integers(1, pt.late_max_days + 1, size=n) if pt.late_max_days > 0
                     else np.zeros(n, dtype=np.int64))
        amounts = np.round(self._r.uniform(0, 10_000, size=n), 2)
        payload_bytes = self.sc.seed_data.payload_bytes
        raw = self._r.bytes(n * (payload_bytes // 2 + 1)).hex()
        sec = now.hour * 3600 + now.minute * 60 + now.second
        out: list[dict[str, Any]] = []
        for i in range(n):
            d = today - timedelta(days=int(late_days[i])) if late[i] else today
            off = i * (payload_bytes + 2)
            out.append({
                "event_id": self.next_id, "key": int(keys[i]), "dt": d.isoformat(),
                "event_ts": f"{d.isoformat()}T{sec // 3600:02d}:{sec // 60 % 60:02d}:{sec % 60:02d}",
                "amount": float(amounts[i]), "status": "new", "version": 0,
                "payload": raw[off:off + payload_bytes],
            })
            self.next_id += 1
        return out


def partition_of(ev: dict[str, Any], n_buckets: int) -> tuple[str, int]:
    return ev["dt"], bucket_long(int(ev["key"]), n_buckets)


# ── rows inserted by MERGE ───────────────────────────────────────────────────

def keys_in_bucket(r: np.random.Generator, bucket: int, n_buckets: int, card: int, n: int
                   ) -> Iterator[int]:
    got = 0
    while got < n:
        for k in r.integers(0, card, size=max(16, (n - got) * n_buckets * 2), dtype=np.int64):
            if bucket_long(int(k), n_buckets) == bucket:
                yield int(k)
                got += 1
                if got == n:
                    return


def merge_insert_rows(sc: Scenario, op_index: int, op_seed: int, partitions: list[tuple[date, int]],
                      n: int) -> list[tuple[Any, ...]]:
    """n new rows spread over the footprint partitions; ids from the operation's range."""
    if n <= 0 or not partitions:
        return []
    r = np.random.Generator(np.random.PCG64(op_seed))
    nb, card = sc.table.n_buckets, sc.seed_data.key_cardinality
    per = [n // len(partitions) + (1 if i < n % len(partitions) else 0) for i in range(len(partitions))]
    base = OP_BASE + op_index * OP_STRIDE
    rows: list[tuple[Any, ...]] = []
    j = 0
    for (d, b), m in zip(partitions, per, strict=False):
        for k in keys_in_bucket(r, b, nb, card, m):
            ts = datetime(d.year, d.month, d.day) + timedelta(seconds=int(r.integers(0, 86400)))
            rows.append((base + j, k, d, ts, float(round(r.uniform(0, 10_000), 2)), "merged", 0,
                         r.bytes(sc.seed_data.payload_bytes // 2).hex()))
            j += 1
    return rows
